import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const site = fileURLToPath(new URL('../', import.meta.url));
const root = fileURLToPath(new URL('../../../', import.meta.url));
const output = join(site, 'public', 'THIRD-PARTY-NOTICES.txt');
const review = 'https://github.com/brendankowitz/nachos/issues/16#issuecomment-6129149981';

const emitted = [
  ['astro', '7.3.5'],
  ['@astrojs/sitemap', '3.7.4'],
  ['@astrojs/starlight', '0.42.4'],
  ['@expressive-code/core', '0.44.2'],
  ['@expressive-code/plugin-frames', '0.44.2'],
  ['@expressive-code/plugin-shiki', '0.44.2'],
  ['@expressive-code/plugin-text-markers', '0.44.2'],
  ['astro-expressive-code', '0.44.2'],
  ['mermaid', '11.17.2'],
  ['starlight-openapi', '0.27.0'],
];

function sha256(text) {
  return createHash('sha256').update(text).digest('hex').toUpperCase();
}

function packageDirectory(name) {
  return join(site, 'node_modules', ...name.split('/'));
}

function findLicenseFiles(directory) {
  const files = readdirSync(directory, { withFileTypes: true })
    .filter((entry) => entry.isFile() && /^(LICENSE|LICENCE|COPYING|NOTICE|COPYRIGHT)(\.|$|-)|^UNLICENSE$/i.test(entry.name))
    .map((entry) => join(directory, entry.name))
    .sort((a, b) => a.localeCompare(b));
  if (!files.length) throw new Error(`No license files found in ${relative(root, directory)}`);
  return files;
}

function readNoticeFile(path) {
  return readFileSync(path, 'utf8').replace(/\r\n?/g, '\n').trimEnd();
}

function renderFile(path) {
  const text = readNoticeFile(path);
  return `File: ${relative(root, path).replaceAll('\\', '/')}\nSHA-256: ${sha256(text + '\n')}\n\n${text}\n`;
}

function generate() {
  const lines = [];
  lines.push('Nachos documentation site third-party notices');
  lines.push('=================================================');
  lines.push('');
  lines.push('This file is generated by docs/site/scripts/notices.mjs. Do not edit it by hand.');
  lines.push(`Reviewed emitted-package evidence: ${review}`);
  lines.push('');
  lines.push('Redistributed npm package notices');
  lines.push('---------------------------------');
  for (const [name, version] of emitted) {
    lines.push('');
    lines.push(`## ${name}@${version}`);
    const packageJsonPath = join(packageDirectory(name), 'package.json');
    if (existsSync(packageJsonPath)) {
      const packageJson = JSON.parse(readFileSync(packageJsonPath, 'utf8'));
      if (packageJson.name !== name || packageJson.version !== version) {
        throw new Error(`Installed ${name} package mismatch: ${packageJson.name}@${packageJson.version}`);
      }
    } else {
      throw new Error(`Installed package is required for ${name}@${version}`);
    }
    const files = findLicenseFiles(packageDirectory(name));
    for (const file of files) lines.push(renderFile(file));
  }
  return lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
}

const generated = generate();
if (process.argv.includes('--check')) {
  if (!existsSync(output)) {
    console.error(`Missing generated notice file: ${relative(root, output)}`);
    process.exit(1);
  }
  const current = readFileSync(output, 'utf8');
  if (current !== generated) {
    console.error(`Stale generated notice file: ${relative(root, output)}`);
    process.exit(1);
  }
  console.log('Third-party notices are up to date.');
} else {
  writeFileSync(output, generated, 'utf8');
  console.log(`Wrote ${relative(root, output)} (${generated.length} bytes).`);
}
