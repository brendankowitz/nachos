import assert from 'node:assert/strict';
import { mkdir, mkdtemp, rm } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import test from 'node:test';
import { createProvenance } from '../integrations/bundle-provenance.mjs';

const site = fileURLToPath(new URL('../', import.meta.url));
test('the known Astro OpenAPI route facade binds its actual installed template', async () => {
  await mkdir(join(site, '.test-runs'), { recursive: true });
  const output = await mkdtemp(join(site, '.test-runs', 'openapi-'));
  try {
    const producer = createProvenance(site);
    await producer.emitGenerated(join(output, 'asset.css'), 'known generated bytes', [
      join(site, 'virtual:astro:page:node_modules/starlight-openapi/routes/static/index@_@astro'),
    ], 'vite-asset');
    const data = await producer.write(output);
    assert.ok(data.sources.some((entry) => entry.path.endsWith('/starlight-openapi/routes/static/index.astro')));
    assert.deepEqual(data.outputs[0].packages, [{ package: 'starlight-openapi', version: '0.27.0' }]);
    await assert.rejects(producer.registerGenerated('unknown', [
      join(site, 'virtual:astro:page:unreviewed/index@_@astro'),
    ]), /ENOENT|Unknown/);
  } finally { await rm(output, { recursive: true, force: true }); }
});
